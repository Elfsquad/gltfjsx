#!/usr/bin/env node
'use strict'
import meow from 'meow'
import { fileURLToPath } from 'url'
import { dirname } from 'path'
import gltfjsx from './src/gltfjsx.js'
import { readPackageUpSync } from 'read-pkg-up'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)

const cli = meow(
  `
	Usage
	  $ npx gltfjsx [Model.glb] [options]

	Options
    --output, -o        Output file name/path
    --types, -t         Add Typescript definitions
    --keepnames, -k     Keep original names
    --keepgroups, -K    Keep (empty) groups, disable pruning
    --bones, -b         Lay out bones declaratively (default: false)
    --meta, -m          Include metadata (as userData)
    --shadows, s        Let meshes cast and receive shadows
    --printwidth, w     Prettier printWidth (default: 120)
    --formatlimit       Skip prettier when the unformatted JSX is longer than this many
                        characters (default: no limit); prettier's heap grows ~190x the JSX
    --precision, -p     Number of fractional digits (default: 3)
    --draco, -d         Draco binary path
    --root, -r          Sets directory from which .gltf file is served
    --url               URL to load the model from, used verbatim in useGLTF() and preload()
    --header            Header comment text, used verbatim instead of the default (which
                        includes the command line, so it differs between runs)
    --instance, -i      Instance re-occuring geometry
    --instanceall, -I   Instance every geometry (for cheaper re-use)
    --exportdefault, -E Use default export
    --transform, -T     Transform the asset for the web (draco, prune, resize)
      --resolution, -R  Resolution for texture resizing (default: 1024)
      --keepmeshes, -j  Do not join compatible meshes
      --keepmaterials, -M Do not palette join materials
      --format, -f      Texture format (default: "webp")
      --simplify, -S    Mesh simplification (default: false)
        --ratio         Simplifier ratio (default: 0)
        --error         Simplifier error threshold (default: 0.0001)
    --console, -c       Log JSX to console, won't produce a file
    --debug, -D         Debug output
`,
  {
    importMeta: import.meta,
    flags: {
      output: { type: 'string', shortFlag: 'o' },
      types: { type: 'boolean', shortFlag: 't' },
      keepnames: { type: 'boolean', shortFlag: 'k' },
      keepgroups: { type: 'boolean', shortFlag: 'K' },
      bones: { type: 'boolean', shortFlag: 'b', default: false },
      shadows: { type: 'boolean', shortFlag: 's' },
      printwidth: { type: 'number', shortFlag: 'p', default: 1000 },
      formatlimit: { type: 'number' },
      meta: { type: 'boolean', shortFlag: 'm' },
      precision: { type: 'number', shortFlag: 'p', default: 3 },
      draco: { type: 'string', shortFlag: 'd' },
      root: { type: 'string', shortFlag: 'r' },
      url: { type: 'string' },
      header: { type: 'string' },
      instance: { type: 'boolean', shortFlag: 'i' },
      instanceall: { type: 'boolean', shortFlag: 'I' },
      transform: { type: 'boolean', shortFlag: 'T' },
      resolution: { type: 'number', shortFlag: 'R', default: 1024 },
      degrade: { type: 'string', shortFlag: 'q', default: '' },
      degraderesolution: { type: 'number', shortFlag: 'Q', default: 512 },
      simplify: { type: 'boolean', shortFlag: 'S', default: false },
      keepmeshes: { type: 'boolean', shortFlag: 'j', default: false },
      keepmaterials: { type: 'boolean', shortFlag: 'M', default: false },
      format: { type: 'string', shortFlag: 'f', default: 'webp' },
      exportdefault: { type: 'boolean', shortFlag: 'E' },
      ratio: { type: 'number', default: 0.75 },
      error: { type: 'number', default: 0.001 },
      console: { type: 'boolean', shortFlag: 'c' },
      debug: { type: 'boolean', shortFlag: 'D' },
    },
    // A misspelt or unsupported flag (for example a newer flag on an older build) must fail with
    // exit 2 rather than be ignored while the run exits 0.
    allowUnknownFlags: false,
  }
)

const { packageJson } = readPackageUpSync({ cwd: __dirname, normalize: false })

if (cli.input.length === 0) {
  console.log(cli.help)
} else {
  const config = {
    ...cli.flags,
    header:
      cli.flags.header ??
      `Auto-generated by: https://github.com/pmndrs/gltfjsx
Command: npx gltfjsx@${packageJson.version} ${process.argv.slice(2).join(' ')}`,
  }
  const file = cli.input[0]
  if (config.url !== undefined && config.url.trim() === '') usageError('--url must not be empty')
  if (config.formatlimit !== undefined && !(Number.isInteger(config.formatlimit) && config.formatlimit >= 0))
    usageError('--formatlimit must be a non-negative integer')
  // The header goes inside a /* */ comment: an empty one would fall back to the parser's default,
  // and a `*/` would end the comment early.
  if (cli.flags.header !== undefined && cli.flags.header === '') usageError('--header must not be empty')
  if (cli.flags.header?.includes('*/')) usageError('--header must not contain */')
  // Logs go to stderr: stdout carries the JSX in --console mode.
  const showLog = (log) => {
    console.error('log:', log)
  }
  try {
    const output = config.output ?? defaultOutput(file, config.types)
    const response = await gltfjsx(file, output, { ...config, showLog, timeout: 0, delay: 1 })
  } catch (e) {
    console.error(config.debug ? e : `gltfjsx: ${e?.message ?? e}`)
    process.exitCode = 1
  }
}

function defaultOutput(file, types) {
  const nameExt = file.match(/[-_\w\d\s]+[.][\w]+$/i)
  if (!nameExt) throw new Error(`cannot derive an output name from ${file}; pass --output`)
  const name = nameExt[0].split('.').slice(0, -1).join('.')
  return name.charAt(0).toUpperCase() + name.slice(1) + (types ? '.tsx' : '.jsx')
}

// Exit 2 for a bad command line, as meow does for an unknown flag.
function usageError(message) {
  console.error(`gltfjsx: ${message}`)
  process.exit(2)
}
