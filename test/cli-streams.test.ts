// G4: logs and debug output go to stderr. stdout is empty when writing a file, and carries
// only the JSX with --console, so `gltfjsx --console model.gltf > model.jsx` is safe.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import path from 'node:path'
import { run, tempDir, writeModel } from './cli-helpers.ts'

test('writing a file prints nothing to stdout, even with --debug', () => {
  const dir = tempDir()
  const out = path.join(dir, 'out.jsx')
  const r = run([writeModel(dir), '--output', out, '--debug'])
  assert.equal(r.code, 0, r.stderr)
  assert.equal(r.stdout, '')
  assert.match(r.stderr, /Auto-generated by/) // the header echo
  assert.match(r.stderr, /pos:/) // the --debug scene dump
  assert.match(r.stderr, /removed/) // the --debug pruning log
})

test('--console prints only the JSX on stdout; debug output goes to stderr', () => {
  const dir = tempDir()
  const r = run([writeModel(dir), '--console', '--debug', '--meta'])
  assert.equal(r.code, 0, r.stderr)
  assert.ok(r.stdout.startsWith('/*\n'), r.stdout.slice(0, 80))
  assert.ok(r.stdout.endsWith("useGLTF.preload('/model.gltf')\n\n"), r.stdout.slice(-80))
  assert.doesNotMatch(r.stdout, /pos:|removed|log:/)
  assert.match(r.stderr, /pos:/)
})
