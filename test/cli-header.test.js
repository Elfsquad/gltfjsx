// G2: --header <text> replaces the default header, whose `Command:` line embeds the argv (and so
// the temp paths), making every run's bytes differ.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import parse from '../src/utils/parser.js'
import { GLTFStructureLoader } from '../src/utils/exports.js'
import { run, tempDir, triangleGltf, writeModel } from './cli-helpers.js'

const URL = 'https://example.invalid/gltfmodels/0f1e2d3c/model.gltf'
// The text that makes the header match what parse() prints with no header option, which is what
// forge-convert-server's vendored copy printed (it never passed one).
const LEGACY_HEADER = 'Auto-generated by: https://github.com/pmndrs/gltfjsx'
const PIPELINE = ['--keepnames', '--keepgroups', '--meta', '--shadows', '--precision', '3']

function convert(args) {
  const dir = tempDir() // a different random directory per run
  const out = path.join(dir, 'out.jsx')
  const r = run([writeModel(dir), '--output', out, ...args])
  return { ...r, dir, jsx: r.code === 0 ? fs.readFileSync(out, 'utf8') : '' }
}

test('--header is printed verbatim and the command line is not', () => {
  const r = convert(['--header', 'Generated by convert-svf', '--url', URL, ...PIPELINE])
  assert.equal(r.code, 0, r.stderr)
  assert.ok(r.jsx.startsWith('/*\nGenerated by convert-svf \n*/\n'), JSON.stringify(r.jsx.slice(0, 60)))
  assert.doesNotMatch(r.jsx, /Command:|npx|gltfjsx@/)
  assert.ok(!r.jsx.includes(r.dir), 'the output names the temp directory')
})

test('two runs in different directories produce identical bytes', () => {
  const args = ['--header', LEGACY_HEADER, '--url', URL, ...PIPELINE]
  const a = convert(args)
  const b = convert(args)
  assert.equal(a.code, 0, a.stderr)
  assert.notEqual(a.dir, b.dir)
  assert.equal(a.jsx, b.jsx)
})

test('--console with --header prints the same bytes as the file (plus console.log newline)', () => {
  const args = ['--header', LEGACY_HEADER, '--url', URL, ...PIPELINE]
  const file = convert(args)
  const dir = tempDir()
  const r = run([writeModel(dir), '--console', ...args])
  assert.equal(r.code, 0, r.stderr)
  assert.equal(r.stdout, file.jsx + '\n')
})

test('the legacy header text gives the bytes of parse() called as forge-convert-server calls it', async () => {
  const gltf = await new Promise((resolve, reject) =>
    new GLTFStructureLoader().parse(JSON.stringify(triangleGltf()), '', resolve, reject)
  )
  const legacy = await parse(gltf, {
    fileName: URL,
    keepnames: true,
    keepgroups: true,
    precision: 3,
    meta: true,
    shadows: true,
  })
  const r = convert(['--header', LEGACY_HEADER, '--url', URL, ...PIPELINE])
  assert.equal(r.code, 0, r.stderr)
  assert.equal(r.jsx, legacy)
})

test('a multi-line --header is kept as is', () => {
  const r = convert(['--header', 'line one\nline two'])
  assert.equal(r.code, 0, r.stderr)
  assert.ok(r.jsx.startsWith('/*\nline one\nline two \n*/\n'))
})

test('without --header the default header with the command line is kept', () => {
  const r = convert([])
  assert.equal(r.code, 0, r.stderr)
  assert.match(r.jsx, /^\/\*\nAuto-generated by: https:\/\/github\.com\/pmndrs\/gltfjsx\nCommand: npx gltfjsx@/)
})

test('a --header that would end the comment is a usage error (exit 2)', () => {
  const r = convert(['--header', 'oops */ alert(1) /*'])
  assert.equal(r.code, 2)
  assert.match(r.stderr, /must not contain \*\//)
})

test('an empty --header is a usage error (exit 2)', () => {
  const r = convert(['--header', ''])
  assert.equal(r.code, 2)
  assert.match(r.stderr, /--header must not be empty/)
})
